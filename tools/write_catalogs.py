def L(id, name, repo, file, license, positive, avoid=(), keywords=(), exclude=(), trigger="",
      strength=1.0, group="style", min_score=None, negative="", suffix=""):
    d = dict(id=id, name=name, repo=repo, file=file, license=license, group=group, strength=strength,
             trigger=trigger, keywords=list(keywords), exclude=list(exclude), positive=list(positive),
             avoid=list(avoid))
    if min_score is not None:
        d["min_score"] = min_score
    if negative:
        d["negative"] = negative
    if suffix:
        d["suffix"] = suffix
    return d


